import json
from pathlib import Path

import pytest
import yaml

from scripts import sweep

BASE = {
    "base_model": "m",
    "lora_r": 16,
    "lora_alpha": 16,
    "num_epochs": 2,
    "learning_rate": 0.0002,
    "mlflow_experiment_name": "billing-sweep",
}
GRID = {"learning_rate": [1e-4, 2e-4, 4e-4], "lora_r": [8, 16], "num_epochs": [1, 2]}


def test_the_grid_is_parsed_with_numbers_as_numbers():
    parsed = sweep.parse_grid(["learning_rate=1e-4,2e-4", "lora_r=8,16", "optimizer=adamw,sgd"])

    assert parsed == {"learning_rate": [1e-4, 2e-4], "lora_r": [8, 16], "optimizer": ["adamw", "sgd"]}
    with pytest.raises(ValueError):
        sweep.parse_grid(["lora_r"])


def test_three_learning_rates_two_ranks_and_two_epoch_counts_make_twelve_runs():
    assert len(sweep.combinations(GRID)) == 12


def test_the_centre_is_the_middle_value_of_each_setting():
    assert sweep.center(GRID) == {"learning_rate": 2e-4, "lora_r": 16, "num_epochs": 2}


def test_twelve_configs_plus_one_repeat_of_the_centre_point_with_another_seed():
    runs = sweep.build(BASE, GRID, seed=42, repeat_center=2)

    assert len(runs) == 13
    repeat = runs[-1]
    assert repeat["center_repeat"] and repeat["seed"] == 7 and repeat["params"] == sweep.center(GRID)
    assert repeat["name"] == "lr0.0002_r16_ep2_seed7"
    assert {run["seed"] for run in runs[:-1]} == {42}


def test_each_config_changes_only_the_swept_settings_a_seed_and_its_names():
    run = sweep.build(BASE, GRID, seed=42)[0]
    config = run["config"]

    assert config["learning_rate"] == 1e-4 and config["lora_r"] == 8 and config["num_epochs"] == 1
    assert config["lora_alpha"] == 16 and config["base_model"] == "m"
    assert config["seed"] == 42 and config["mlflow_run_name"] == run["name"]
    assert config["output_dir"] == f"./runs/axolotl/{run['name']}"


def test_a_setting_the_base_does_not_have_is_refused():
    with pytest.raises(ValueError, match="no warmup_steps"):
        sweep.build(BASE, {"warmup_steps": [1, 2]}, seed=1)


def test_the_configs_and_a_manifest_are_written(tmp_path):
    base = tmp_path / "base.yml"
    base.write_text(yaml.safe_dump(BASE))
    out = tmp_path / "sweep"

    assert (
        sweep.main(
            [
                str(base),
                "--grid",
                "learning_rate=1e-4,2e-4,4e-4",
                "lora_r=8,16",
                "num_epochs=1,2",
                "--seed",
                "42",
                "--repeat-center",
                "2",
                "--out",
                str(out),
            ]
        )
        == 0
    )

    files = sorted(path.name for path in out.glob("*.yml"))
    assert len(files) == 13 and "lr0.0002_r16_ep2_seed7.yml" in files
    first = (out / files[0]).read_text()
    assert first.startswith("# generated by scripts/sweep.py")
    assert yaml.safe_load(first)["seed"] == 42
    manifest = json.loads((out / "sweep.json").read_text())
    assert len(manifest["runs"]) == 13 and sum(run["center_repeat"] for run in manifest["runs"]) == 1


def test_the_committed_sweep_is_what_the_generator_makes_from_the_base_config(tmp_path):
    root = Path(__file__).resolve().parents[1] / "configs" / "axolotl"
    args = [
        "--grid",
        "learning_rate=1e-4,2e-4,4e-4",
        "lora_r=8,16",
        "num_epochs=1,2",
        "--seed",
        "42",
        "--repeat-center",
        "2",
    ]

    assert sweep.main(["configs/axolotl/billing-qlora.yml", *args, "--out", str(tmp_path)]) == 0

    committed = sorted(path.name for path in (root / "sweep-billing").glob("*"))
    assert committed == sorted(path.name for path in tmp_path.glob("*")) and len(committed) == 14
    for name in committed:
        assert (root / "sweep-billing" / name).read_text() == (tmp_path / name).read_text()

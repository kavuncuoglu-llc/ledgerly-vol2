import argparse
import json
import sys
from itertools import product
from pathlib import Path

GENERATED = "# generated by scripts/sweep.py from {base}: edit the base config and regenerate, never this file\n"


def coerce(text: str):
    for cast in (int, float):
        try:
            return cast(text)
        except ValueError:
            continue
    return text


def parse_grid(items: list[str]) -> dict[str, list]:
    grid = {}
    for item in items:
        key, _, values = item.partition("=")
        if not key or not values:
            raise ValueError(f"{item!r} is not name=value,value")
        grid[key] = [coerce(value) for value in values.split(",")]
    return grid


def combinations(grid: dict[str, list]) -> list[dict]:
    return [dict(zip(grid, values, strict=True)) for values in product(*grid.values())]


def center(grid: dict[str, list]) -> dict:
    return {key: values[len(values) // 2] for key, values in grid.items()}


def short(key: str) -> str:
    return {"learning_rate": "lr", "lora_r": "r", "num_epochs": "ep"}.get(key, key)


def name_for(params: dict, seed: int | None = None) -> str:
    base = "_".join(f"{short(key)}{value}" for key, value in params.items())
    return base if seed is None else f"{base}_seed{seed}"


def build(
    base: dict, grid: dict[str, list], seed: int, repeat_center: int = 1, repeat_seed_start: int = 7
) -> list[dict]:
    unknown = [key for key in grid if key not in base]
    if unknown:
        raise ValueError(f"the base config has no {', '.join(unknown)} to sweep")
    runs = []
    for params in combinations(grid):
        runs.append({"name": name_for(params), "params": params, "seed": seed, "center_repeat": False})
    middle = center(grid)
    for extra in range(max(0, repeat_center - 1)):
        repeat_seed = repeat_seed_start + extra
        runs.append(
            {"name": name_for(middle, repeat_seed), "params": middle, "seed": repeat_seed, "center_repeat": True}
        )
    for run in runs:
        config = {**base, **run["params"], "seed": run["seed"]}
        config["output_dir"] = f"./runs/axolotl/{run['name']}"
        config["mlflow_run_name"] = run["name"]
        run["config"] = config
    return runs


def write(runs: list[dict], out: Path, base_path: str) -> None:
    import yaml

    out.mkdir(parents=True, exist_ok=True)
    for run in runs:
        text = GENERATED.format(base=base_path) + yaml.safe_dump(run["config"], sort_keys=False)
        (out / f"{run['name']}.yml").write_text(text)
    manifest = [{key: run[key] for key in ("name", "params", "seed", "center_repeat")} for run in runs]
    (out / "sweep.json").write_text(json.dumps({"base": base_path, "runs": manifest}, indent=2) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="One Axolotl config per point of a small grid, with fixed seeds")
    parser.add_argument("base", help="the base Axolotl config")
    parser.add_argument("--grid", nargs="+", required=True, help="learning_rate=1e-4,2e-4 lora_r=8,16 ...")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--repeat-center", type=int, default=2, help="runs of the centre point in all, with different seeds"
    )
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)

    import yaml

    base = yaml.safe_load(Path(args.base).read_text())
    runs = build(base, parse_grid(args.grid), args.seed, args.repeat_center)
    write(runs, args.out, args.base)
    repeats = sum(run["center_repeat"] for run in runs)
    print(
        f"{len(runs) - repeats} configs, plus {repeats} repeat(s) of the centre point {name_for(center(parse_grid(args.grid)))} → {args.out}"  # noqa: E501
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
